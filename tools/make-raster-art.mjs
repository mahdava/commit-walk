// Builds hooks/raster-art.ts, the welcome art, from assets/logo.png.
//
//   node tools/make-raster-art.mjs [path/to/sharp]
//
// Needs sharp (npm i -g sharp, or pass the path of an installed copy). Each
// Raster cell is a half block: the top pixel as foreground, the bottom as
// background, so a cell shows two pixels. The logo's white becomes the
// terminal's own background; its black outline becomes the terminal's text
// colour, so the art reads on dark and light themes.

import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const sharp = require(process.argv[2] ?? 'sharp')

const DEFAULT = 0x01000000 // the terminal's own colour, foreground or background
const CLEAR = -2 // see-through: the logo's white
const OUTLINE = -1 // the logo's black: drawn in the terminal's text colour
const UPPER = 0x2580 // ▀
const LOWER = 0x2584 // ▄
const FULL = 0x2588 // █

const pixel = (r, g, b) => (r > 232 && g > 232 && b > 232 ? CLEAR : r + g + b < 140 ? OUTLINE : (r << 16) | (g << 8) | b)

/** One cell's [codePoint, foreground, background] from its two pixels. */
function cell(top, bottom) {
  if (top === CLEAR && bottom === CLEAR) return [0x20, DEFAULT, DEFAULT]
  if (top === OUTLINE && bottom === OUTLINE) return [FULL, DEFAULT, DEFAULT]
  const colour = p => (p === OUTLINE || p === CLEAR ? DEFAULT : p)
  if (top === CLEAR) return [LOWER, colour(bottom), DEFAULT]
  if (bottom === CLEAR) return [UPPER, colour(top), DEFAULT]
  // The text colour can only be a foreground: an outline below takes the lower half block.
  if (bottom === OUTLINE) return [LOWER, DEFAULT, top]
  return [UPPER, colour(top), colour(bottom)]
}

const FLOWER = { left: 40, top: 60, width: 520, height: 348 }
const LOGO = { left: 20, top: 60, width: 560, height: 472 }
const variants = [
  { name: 'LOGO_80', what: 'the whole logo with its title', crop: LOGO, columns: 80 },
  { name: 'LOGO_60', what: 'the whole logo with its title', crop: LOGO, columns: 60 },
  { name: 'FLOWER_60', what: 'the flower and the commit line', crop: FLOWER, columns: 60 },
  { name: 'FLOWER_40', what: 'the flower and the commit line', crop: FLOWER, columns: 40 },
]

let out = `// Generated by tools/make-raster-art.mjs from assets/logo.png: do not edit by hand.
// Raster cells, row-major, base64 of little-endian u32 [codePoint, foreground, background].

export type RasterArt = { columns: number; rows: number; cells: string; alt: string }
`
for (const v of variants) {
  const pixels = Math.round((v.columns * v.crop.height) / v.crop.width / 2) * 2
  const rows = pixels / 2
  const { data } = await sharp(join(root, 'assets/logo.png'))
    .extract(v.crop).resize(v.columns, pixels, { kernel: 'lanczos3', fit: 'fill' }).removeAlpha().raw()
    .toBuffer({ resolveWithObject: true })
  const at = (x, y) => { const i = (y * v.columns + x) * 3; return pixel(data[i], data[i + 1], data[i + 2]) }
  const words = new Uint32Array(v.columns * rows * 3)
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < v.columns; c++) words.set(cell(at(c, 2 * r), at(c, 2 * r + 1)), (r * v.columns + c) * 3)
  }
  const cells = Buffer.from(words.buffer).toString('base64')
  out += `
/** ${v.what}, ${v.columns} × ${rows} cells. */
export const ${v.name}: RasterArt = {
  columns: ${v.columns},
  rows: ${rows},
  alt: 'Commit Walk: a sunflower in sneakers walking a line of commits',
  cells: '${cells}',
}
`
}
writeFileSync(join(root, 'hooks/raster-art.ts'), out)
console.log('wrote hooks/raster-art.ts')
